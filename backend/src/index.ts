// Every response carries a request id so an operator can correlate a user
// report with a log line. The identifier is generated by the edge and never
// contains user data.
app.use("*", async (c, next) => {
  const requestId = c.req.header("CF-Ray") ?? crypto.randomUUID();
  c.set("requestId", requestId);
  c.header("X-Request-Id", requestId);
  await next();
});

app.onError((error, c) => {
  const requestId = c.get("requestId") ?? "unknown";
  if (error instanceof HTTPException) {
    const tooLarge = error.status === 413;
    return fail(c, { code: tooLarge ? "PAYLOAD_TOO_LARGE" : "HTTP_ERROR", message: tooLarge ? "حجم درخواست بیشتر از حد مجاز است" : "درخواست قابل پردازش نیست", requestId }, error.status);
  }
  // UUIDv4 values in preference/recommendation URL paths are bearer capabilities.
  // Keep route-level observability without copying those identifiers into logs.
  const safePath = c.req.path.replace(/[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}/ig, ":id");
  console.error("api_error", { requestId, path: safePath, errorType: error.name });
  return fail(c, { code: "INTERNAL_ERROR", message: "درخواست با خطا مواجه شد", requestId }, 500);
});

function isAdmin(c: Context<{ Bindings: Env; Variables: { requestId: string } }>): boolean {
  const token = c.env.ADMIN_INGEST_TOKEN;
  return Boolean(token) && c.req.header("Authorization") === `Bearer ${token}`;
}

/** Every error response carries the request id so an operator can correlate it with the logs. */
function fail(c: Context<{ Bindings: Env; Variables: { requestId: string } }>, error: { code: string; message: string; details?: unknown; requestId?: string }, status: ContentfulStatusCode) {
  return c.json({ error: { ...error, requestId: error.requestId ?? c.get("requestId") ?? "unknown" } }, status);
}

