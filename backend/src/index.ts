  try { return c.json(await importListings(c.env,"manual",body.listings)); }
  catch (error) {
    if (error instanceof IngestionPermissionError) return fail(c, {code:error.code,message:error.message}, 403);
    return fail(c, {code:"INGEST_FAILED",message:"ورود آگهی‌ها انجام نشد؛ وضعیت پایگاه داده را بررسی کنید"}, 500);
  }
