/**
 * Searches the sources for the criteria of the seeker and returns the
 * matching listings.
 *
 * The server reads the source pages at this moment and keeps them only in a
 * short lived cache, so a repeated search does not ask the source again. What
 * the seeker learns is kept on the seeker's device.
 */
app.post("/api/search/live", async c => {
  const body = await c.req.json().catch(() => null);
  const parsed = preferencesSchema.safeParse(body);
  if (!parsed.success) return fail(c, { code: "VALIDATION_ERROR", message: "اطلاعات جست‌وجو معتبر نیست", details: parsed.error.flatten() }, 400);
  const p = parsed.data;
  const criteria = {
    transactionType: p.transactionType,
    city: p.city,
    propertyTypes: p.propertyTypes,
    neighborhoods: p.neighborhoods,
    budgetMin: p.budgetMin,
    budgetMax: p.budgetMax,
    minBedrooms: p.minBedrooms,
    minAreaM2: p.minAreaM2,
    mustHave: p.mustHave,
    avoid: p.avoid,
  };
  try {
    const result = await searchLive(c.env, criteria, {
      maxPages: Math.max(1, Math.min(12, Number(c.req.query("maxPages")) || 6)),
      limit: Math.max(1, Math.min(100, Number(c.req.query("limit")) || 50)),
      inlineDetailLimit: Math.max(0, Math.min(12, Number(c.req.query("details") ?? "3"))),
    });
    // The remaining listing pages are read after the answer was sent, so the
    // prices arrive a little later without making the seeker wait.
    const pageIds = result.pages.filter((page) => page.status === "ok" && page.items > 0).map((page) => page.pageId);
    if (pageIds.length > 0) {
      const background = () => enrichPagesInBackground(c.env, pageIds, {});
      try {
        c.executionCtx.waitUntil(background());
      } catch {
        void background();
      }
    }
    return c.json(result);
  } catch (error) {
    return fail(c, { code: "SEARCH_FAILED", message: error instanceof Error ? error.message : "جست‌وجو انجام نشد" }, 502);
  }
});

app.put("/api/preferences/:id", async c => {
  const id = c.req.param("id").trim();
  // Preference IDs are short-lived, anonymous bearer capabilities generated with
  // crypto.randomUUID() by the clients. Requiring UUIDv4 prevents caller-chosen
  // predictable identifiers; insert-only semantics prevent replacement by ID.
  if (!/^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(id)) return fail(c, { code:"INVALID_ID", message:"شناسه نامعتبر است" }, 400);
  const body = await c.req.json().catch(() => null);
  const parsed = preferencesSchema.safeParse(body);
  if (!parsed.success) return fail(c, { code:"VALIDATION_ERROR", message:"اطلاعات ترجیحات معتبر نیست", details:parsed.error.flatten() }, 400);
  const p = parsed.data;
  const ttlHours = Math.max(1, Number(c.env.PREFERENCE_TTL_HOURS) || 24);
  const expiresAt = new Date(Date.now() + ttlHours * 3_600_000).toISOString();
  const saved = await c.env.DB.prepare(`INSERT INTO user_preferences(id,budget_min,budget_max,property_types,transaction_type,city,neighborhoods,min_bedrooms,min_area_m2,max_commute_minutes,must_have,avoid,expires_at,updated_at)
    VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,CURRENT_TIMESTAMP) ON CONFLICT(id) DO NOTHING`)
    .bind(id,p.budgetMin ?? null,p.budgetMax ?? null,JSON.stringify(p.propertyTypes),p.transactionType,p.city ?? null,JSON.stringify(p.neighborhoods),p.minBedrooms ?? null,p.minAreaM2 ?? null,p.maxCommuteMinutes ?? null,JSON.stringify(p.mustHave),JSON.stringify(p.avoid),expiresAt).run();
  if (saved.meta.changes === 0) return fail(c, { code:"PREFERENCE_ID_ALREADY_USED", message:"این شناسه قبلاً استفاده شده است؛ جست‌وجوی تازه‌ای آغاز کنید" }, 409);
  return c.json({ id, preferences:p, expiresAt });
});

app.get("/api/listings", async c => {
  const parsed = searchSchema.safeParse(Object.fromEntries(new URL(c.req.url).searchParams));
  if (!parsed.success) return fail(c, {code:"VALIDATION_ERROR",message:"فیلترهای جست‌وجو معتبر نیست",details:parsed.error.flatten()}, 400);
  const p = parsed.data;
  const where = ["status='active'", "(expires_at IS NULL OR expires_at > ?)"], values: (string|number)[] = [new Date().toISOString()];
  if (p.city) { where.push("city = ? COLLATE NOCASE"); values.push(p.city); }
  if (p.transactionType) { where.push("transaction_type = ?"); values.push(p.transactionType); }
  if (p.propertyType) { where.push("property_type = ? COLLATE NOCASE"); values.push(p.propertyType); }
  if (p.minPrice !== undefined) { where.push("price >= ?"); values.push(p.minPrice); }
  if (p.maxPrice !== undefined) { where.push("price <= ?"); values.push(p.maxPrice); }
  if (p.minAreaM2 !== undefined) { where.push("area_m2 >= ?"); values.push(p.minAreaM2); }
  if (p.minBedrooms !== undefined) { where.push("bedrooms >= ?"); values.push(p.minBedrooms); }
  if (p.q) { where.push("(title LIKE ? ESCAPE char(92) OR description LIKE ? ESCAPE char(92) OR neighborhood LIKE ? ESCAPE char(92))"); const q = `%${p.q.replace(/[\\%_]/g, "\\$&")}%`; values.push(q,q,q); }
  const clause = where.join(" AND ");
  const totalRow = await c.env.DB.prepare(`SELECT COUNT(*) AS total FROM listings WHERE ${clause}`).bind(...values).first<{total:number}>();
  const result = await c.env.DB.prepare(`SELECT * FROM listings WHERE ${clause} ORDER BY last_seen_at DESC LIMIT ? OFFSET ?`).bind(...values,p.limit,p.offset).all<Record<string,unknown>>();
  const maxAge = Math.max(1, Number(c.env.MAX_LISTING_AGE_DAYS) || 90);
  // Stale records are returned but marked, so the client never implies that
  // their availability is confirmed.
  const listings = result.results.map(r => toPublicListing(r, maxAge));
  const total = Number(totalRow?.total ?? 0);
  return c.json({
    items: listings,
    limit: p.limit,
    offset: p.offset,
    count: listings.length,
    staleCount: listings.filter((listing) => listing.stale).length,
    total,
    hasMore: p.offset + listings.length < total,
  });
});

app.post("/api/recommendations/:preferenceId", async c => {
  const row = await c.env.DB.prepare("SELECT * FROM user_preferences WHERE id=?").bind(c.req.param("preferenceId")).first<Record<string,unknown>>();
  if (!row) return fail(c, {code:"PREFERENCES_NOT_FOUND",message:"ابتدا ترجیحات را ثبت کنید"}, 404);
  const prefs = { budgetMin: row.budget_min == null ? undefined : Number(row.budget_min), budgetMax: row.budget_max == null ? undefined : Number(row.budget_max), propertyTypes:JSON.parse(String(row.property_types)) as string[], transactionType:row.transaction_type as "buy"|"rent", city:row.city == null ? undefined : String(row.city), neighborhoods:JSON.parse(String(row.neighborhoods)) as string[], minBedrooms:row.min_bedrooms == null ? undefined : Number(row.min_bedrooms), minAreaM2:row.min_area_m2 == null ? undefined : Number(row.min_area_m2), maxCommuteMinutes:row.max_commute_minutes == null ? undefined : Number(row.max_commute_minutes), mustHave:JSON.parse(String(row.must_have)) as string[], avoid:JSON.parse(String(row.avoid)) as string[] };
  const result = await c.env.DB.prepare("SELECT * FROM listings WHERE status='active' AND transaction_type=? AND (expires_at IS NULL OR expires_at > ?) ORDER BY last_seen_at DESC LIMIT 500").bind(prefs.transactionType, new Date().toISOString()).all<Record<string,unknown>>();
  const maxAge = Math.max(1, Number(c.env.MAX_LISTING_AGE_DAYS) || 90);
  const eligible = result.results.map(r => ({ row: r, listing: toPublicListing(r, maxAge) }))
    .filter(({ listing }) => isEligibleListing(listing,prefs))
    .map(({ row, listing }) => {
      const scored = scoreListing(listing,prefs);
      const reasons = listing.stale ? [...scored.reasons, "STALE_LISTING" as const] : scored.reasons;
      return {
        ...scored,
        reasons,
        reasonLabels: reasons.map((reason) => REASON_LABELS[reason]),
        freshness: freshnessScore(String(row.last_seen_at)),
      };
    })
    .sort((a,b) => b.score - a.score || b.freshness - a.freshness || a.listing.id.localeCompare(b.listing.id));
  const total = eligible.length;
  const limit = Math.max(1, Math.min(100, Number(c.req.query("limit")) || 50));
  const offset = Math.max(0, Number(c.req.query("offset")) || 0);
  return c.json({
    preferenceId:c.req.param("preferenceId"),
    scoring:{ version:1, weights:"Configured by available preferences; score normalized to 0-100" },
    items: eligible.slice(offset, offset + limit),
    total,
    limit,
    offset,
    hasMore: offset + Math.min(limit, Math.max(0, total - offset)) < total,
  });
});

