/**
 * Withdraws or deletes a listing (FR-14). The default action is a soft
 * withdrawal that keeps the record and its provenance for audit; `purge`
 * performs the hard deletion that the retention policy defines.
 */
app.delete("/api/listings/:id", async c => {
  if (!isAdmin(c)) return fail(c, { code: "UNAUTHORIZED", message: "اجازه دسترسی ندارید" }, 401);
  const id = c.req.param("id").trim();
  const purge = c.req.query("purge") === "true";
  const body = await c.req.json().catch(() => null);
  const reason = typeof body === "object" && body && "reason" in body && typeof (body as { reason?: unknown }).reason === "string"
    ? String((body as { reason: string }).reason).slice(0, 200)
    : "unspecified";
  const existing = await c.env.DB.prepare("SELECT id FROM listings WHERE id=?").bind(id).first<{ id: string }>();
  if (!existing) return fail(c, { code: "LISTING_NOT_FOUND", message: "آگهی یافت نشد" }, 404);
  if (purge) {
    await c.env.DB.prepare("DELETE FROM listings WHERE id=?").bind(id).run();
  } else {
    await c.env.DB.prepare("UPDATE listings SET status='removed', updated_at=CURRENT_TIMESTAMP WHERE id=?").bind(id).run();
  }
  const runId = crypto.randomUUID();
  await c.env.DB.prepare("INSERT INTO ingestion_runs(id, adapter, received_count, inserted_count, updated_count, skipped_count, status, finished_at, message) VALUES(?,?,?,?,?,?,?,CURRENT_TIMESTAMP,?)")
    .bind(runId, "admin_action", 1, 0, purge ? 0 : 1, 0, "completed", `listing ${purge ? "purged" : "withdrawn"}: ${reason}`).run();
  return c.json({ id, action: purge ? "purged" : "withdrawn", reason, runId });
});

